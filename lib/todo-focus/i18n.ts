const dictionaries: Record<AppLanguage, Record<TodoI18nKey, string>> = { 'zh-CN': zhCN, en }

const MONTH_NAMES = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

export const todoT = (language: AppLanguage, key: TodoI18nKey, params?: Record<string, string | number>) => {
  const template = dictionaries[language]?.[key] ?? zhCN[key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_match, name) => {
    if (name === 'monthName' && params.month !== undefined) return MONTH_NAMES[Number(params.month) - 1] ?? ''
    return String(params[name] ?? '')
  })
}
