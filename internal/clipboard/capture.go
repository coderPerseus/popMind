const (
	utiText8    = "public.utf8-plain-text"
	utiText16   = "public.utf16-plain-text"
	utiHTML     = "public.html"
	utiRTF      = "public.rtf"
	utiRTFD     = "com.apple.flat-rtfd"
	utiURL      = "public.url"
	utiURLName  = "public.url-name"
	utiFileURL  = "public.file-url"
	utiPNG      = "public.png"
	pollEvery   = 250 * time.Millisecond
	emptyRetry  = 8
	maxRawImage = 256 << 20
)

var (
	imagePriority = []string{utiPNG, "public.tiff", "public.jpeg", "public.heic"}
	metaTypes     = []string{"org.nspasteboard.source", "com.apple.is-remote-clipboard", Marker}
	allowTypes    = append(append([]string{utiText8, utiText16, utiHTML, utiRTF, utiRTFD, utiURL, utiURLName}, imagePriority...),
		append([]string{utiFileURL}, metaTypes...)...)
	itemIDPattern = regexp.MustCompile(`(?i)^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)
	appPrivate    = regexp.MustCompile(`/Library/(?:Containers|Group Containers|Caches|Application Support)/|^/(?:private/)?(?:var/folders|tmp)/`)
	imageFileUTIs = map[string]string{"png": utiPNG, "jpg": "public.jpeg", "jpeg": "public.jpeg", "heic": "public.heic",
		"heif": "public.heic", "tif": "public.tiff", "tiff": "public.tiff", "gif": "com.compuserve.gif", "bmp": "com.microsoft.bmp"}
)

func isImageType(t string) bool { return slices.Contains(imagePriority, t) }

func isVolatile(t string) bool {
	return strings.HasPrefix(t, "dyn.") || strings.HasPrefix(t, "com.microsoft.ole.source.") || slices.Contains([]string{
		"org.chromium.source-url", "org.chromium.internal.source-rfh-token", "org.chromium.web-custom-data",
		"com.apple.WebKit.custom-pasteboard-data", "com.apple.linkpresentation.metadata"}, t)
}

func isStorable(t string) bool {
	return slices.Contains(allowTypes, t) && !slices.Contains(metaTypes, t) && !isVolatile(t)
}

// Watcher polls the pasteboard and stores what is copied.
type Watcher struct {
	store    *Store
	stop     chan struct{}
	last     int64
	retryCC  int64
	retryN   int
	OnIngest func(id string, kind string)
}

// StartWatcher starts capturing into store.
func StartWatcher(store *Store) *Watcher {
	w := &Watcher{store: store, stop: make(chan struct{}), last: native.ClipboardChangeCount()}
	go w.loop()
	logx.Info("[clip-capture] started", "pollMs", pollEvery.Milliseconds(), "changeCount", w.last)
	return w
}

// Stop stops capturing.
func (w *Watcher) Stop() { close(w.stop) }

func (w *Watcher) loop() {
	t := time.NewTicker(pollEvery)
	defer t.Stop()
	for {
		select {
		case <-w.stop:
			return
		case <-t.C:
			cc := native.ClipboardChangeCount()
			if cc < 0 || cc == w.last || native.IsClipboardFallbackActive() {
				continue
			}
			func() {
				defer func() {
					if r := recover(); r != nil {
						logx.Error("[clip-capture] panic", "panic", r)
					}
				}()
				w.handle(cc)
			}()
		}
	}
}

func skip(reason string, kv ...any) {
	logx.Info("[clip-capture] skipped", append([]any{"reason", reason}, kv...)...)
}

func (w *Watcher) handle(cc int64) {
	started := time.Now()
	previous := w.last
	w.last = cc
	s := CurrentSettings()
	nowMs := now()
	if r := privacyPrecondition(s, nowMs, "", "", flags{}); r != "" {
		skip(r)
		return
	}
	front := native.Frontmost()
	maxBytes := max(1, s.MaxItemMb) * 1024 * 1024
	snap, err := native.ReadPasteboard(native.PasteboardReadOptions{AllowTypes: allowTypes, MaxBytes: maxBytes, MaxImageBytes: maxRawImage})
	if err != nil {
		skip("read-failed")
		return
	}
	w.last = snap.ChangeCount
	if len(snap.AllTypes) == 0 && !snap.TooLarge {
		if w.retryCC == snap.ChangeCount {
			w.retryN++
		} else {
			w.retryCC, w.retryN = snap.ChangeCount, 1
		}
		if w.retryN <= emptyRetry {
			w.last = previous
			return
		}
		skip("empty")
		return
	}
	if snap.PopMindMarker != nil {
		if itemIDPattern.MatchString(*snap.PopMindMarker) {
			w.store.MarkUsed(*snap.PopMindMarker)
		} else {
			skip("own-marker")
		}
		return
	}
	if snap.TooLarge {
		skip("too-large", "bytes", snap.TotalBytes)
		return
	}
	if r := privacyPrecondition(s, nowMs, snap.SourceBundleID, front.BundleID,
		flags{snap.Flags.Concealed, snap.Flags.Transient, snap.Flags.AutoGenerated}); r != "" {
		skip(r, "source", snap.SourceBundleID, "frontmost", front.BundleID)
		return
	}
	if slices.Contains(snap.AllTypes, "com.microsoft.Link-Source") && slices.Contains(snap.AllTypes, "com.microsoft.ObjectLink") {
		skip("office-link")
		return
	}
	cand := extract(snap.Items)
	texts := append([]string{}, cand.texts...)
	if cand.url != "" {
		texts = append(texts, cand.url)
	}
	if r := privacyContent(s, texts); r != "" {
		skip(r)
		return
	}
	sourceID := cmpOr(snap.SourceBundleID, front.BundleID)
	sourceName := ""
	if sourceID != "" {
		if front.BundleID == sourceID && front.Name != "" {
			sourceName = front.Name
		} else {
			parts := strings.Split(sourceID, ".")
			sourceName = parts[len(parts)-1]
		}
	}
	rec, reason := build(cand, int64(maxBytes))
	if reason != "" {
		skip(reason, "items", len(snap.Items))
		return
	}
	rec.CopiedAt, rec.SourceID, rec.SourceName, rec.IsRemote = nowMs, sourceID, sourceName, snap.Flags.Remote
	id, inserted, err := w.store.Ingest(rec)
	if err != nil {
		logx.Warn("[clip-capture] ingest failed", "err", err)
		return
	}
	logx.Info("[clip-capture] ingested", "inserted", inserted, "kind", rec.Kind, "bytes", rec.ByteSize, "source", sourceID,
		"ms", time.Since(started).Milliseconds())
	if w.OnIngest != nil {
		w.OnIngest(id, rec.Kind)
	}
}

type candidate struct {
	texts     []string
	html      string
	hasRTF    bool
	rtf       []byte
	url       string
	files     []string
	imageReps []Representation
	reps      []Representation
}

func decodeText(uti string, data []byte) string {
	var s string
	if uti == utiText16 && len(data) >= 2 {
		u := make([]uint16, len(data)/2)
		for i := range u {
			u[i] = binary.LittleEndian.Uint16(data[2*i:])
		}
		s = string(utf16.Decode(u))
	} else {
		s = string(data)
	}
	return strings.TrimPrefix(strings.ReplaceAll(s, "\x00", ""), "\uFEFF")
}

func parseFileURLs(data []byte) []string {
	var paths []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "file://") || strings.HasPrefix(line, "file:///.file/id=") {
			continue
		}
		if u, err := url.Parse(line); err == nil && u.Path != "" {
			paths = append(paths, u.Path)
		}
	}
	return paths
}

func extract(items []native.PasteboardItem) candidate {
	var c candidate
	for idx, item := range items {
		hasUTF8 := false
		for _, r := range item.Representations {
			hasUTF8 = hasUTF8 || (r.Type == utiText8 && len(r.Data) > 0)
		}
		itemText, gotText := "", false
		for _, r := range item.Representations {
			if len(r.Data) == 0 || !isStorable(r.Type) || (r.Type == utiText16 && hasUTF8) {
				continue
			}
			c.reps = append(c.reps, Representation{ItemIndex: idx, UTI: r.Type, Data: r.Data})
			switch {
			case r.Type == utiText8 || r.Type == utiText16:
				if t := decodeText(r.Type, r.Data); strings.TrimSpace(t) != "" && !gotText {
					itemText, gotText = t, true
				}
			case r.Type == utiHTML:
				if c.html == "" {
					c.html = string(r.Data)
				}
			case r.Type == utiRTF || r.Type == utiRTFD:
				c.hasRTF = true
				if r.Type == utiRTF && c.rtf == nil {
					c.rtf = r.Data
				}
			case r.Type == utiURL:
				if c.url == "" {
					c.url = strings.TrimSpace(strings.Split(string(r.Data), "\n")[0])
				}
			case r.Type == utiFileURL:
				c.files = append(c.files, parseFileURLs(r.Data)...)
			case isImageType(r.Type):
				c.imageReps = append(c.imageReps, Representation{ItemIndex: idx, UTI: r.Type, Data: r.Data})
			}
		}
		if gotText {
			c.texts = append(c.texts, itemText)
		}
	}
	slices.SortStableFunc(c.imageReps, func(a, b Representation) int {
		return slices.Index(imagePriority, a.UTI) - slices.Index(imagePriority, b.UTI)
	})
	c.files = slices.Compact(c.files)
	return c
}

var (
	scriptStyle = regexp.MustCompile(`(?is)<(script|style)[\s\S]*?</(script|style)>`)
	brTag       = regexp.MustCompile(`(?i)<br\s*/?>`)
	blockEnd    = regexp.MustCompile(`(?i)</(p|div|li|tr|h[1-6])>`)
	anyTag      = regexp.MustCompile(`<[^>]+>`)
)

func htmlToText(h string) string {
	h = scriptStyle.ReplaceAllString(h, "")
	h = brTag.ReplaceAllString(h, "\n")
	h = blockEnd.ReplaceAllString(h, "\n")
	return html.UnescapeString(anyTag.ReplaceAllString(h, ""))
}

var (
	rtfHex     = regexp.MustCompile(`(?i)\\'([0-9a-f]{2})`)
	rtfGroups  = regexp.MustCompile(`\{\\\*[^{}]*\}`)
	rtfPar     = regexp.MustCompile(`\\(?:par|line)\b ?`)
	rtfControl = regexp.MustCompile(`(?i)\\[a-z]+-?\d* ?`)
)

func rtfToText(r string) string {
	r = rtfHex.ReplaceAllStringFunc(r, func(m string) string {
		var b byte
		for _, ch := range strings.ToLower(m[2:]) {
			b = b*16 + byte(strings.IndexRune("0123456789abcdef", ch))
		}
		return string(rune(b))
	})
	r = rtfGroups.ReplaceAllString(r, "")
	r = rtfPar.ReplaceAllString(r, "\n")
	r = rtfControl.ReplaceAllString(r, "")
	return strings.NewReplacer("{", "", "}", "").Replace(r)
}

// pngSize reads the size from a PNG header.
func pngSize(data []byte) (int, int, bool) {
	if len(data) < 24 || !bytes.Equal(data[:8], []byte("\x89PNG\r\n\x1a\n")) {
		return 0, 0, false
	}
	return int(binary.BigEndian.Uint32(data[16:20])), int(binary.BigEndian.Uint32(data[20:24])), true
}

type decoded struct {
	png       []byte
	w, h, idx int
}

func decodeImage(reps []Representation) *decoded {
	for _, r := range reps {
		if r.UTI == utiPNG {
			if w, h, ok := pngSize(r.Data); ok {
				return &decoded{r.Data, w, h, r.ItemIndex}
			}
		}
		if out, err := native.ConvertImageToPNG(r.Data); err == nil && len(out.PNG) > 0 && out.Width > 0 {
			return &decoded{out.PNG, out.Width, out.Height, r.ItemIndex}
		}
	}
	return nil
}

func sumBytes(reps []Representation) int64 {
	var n int64
	for _, r := range reps {
		n += int64(len(r.Data))
	}
	return n
}

func imageRecord(d *decoded, other []Representation, html string) Record {
	reps := append(append([]Representation{}, other...), Representation{ItemIndex: d.idx, UTI: utiPNG, Data: d.png})
	return Record{Kind: KindImage, Fingerprint: imageFingerprint(d.png), Title: DeriveTitle(KindImage, "", "", "", nil, 0, d.w, d.h),
		Preview: Preview(KindImage, "", "", "", nil, d.w, d.h), HTML: html, ImagePNG: d.png, ImageWidth: d.w, ImageHeight: d.h,
		Reps: reps, ByteSize: sumBytes(reps)}
}

// build turns a candidate into a record, or returns why it is not stored (normalize.ts).
func build(c candidate, maxBytes int64) (Record, string) {
	// An app-private image file (WeChat, QQ…) is an image copy, not a file the user picked.
	if len(c.files) == 1 && appPrivate.MatchString(c.files[0]) {
		ext := strings.ToLower(c.files[0][strings.LastIndex(c.files[0], ".")+1:])
		if uti, ok := imageFileUTIs[ext]; ok {
			if info, err := os.Stat(c.files[0]); err == nil && info.Size() > 0 && info.Size() <= maxRawImage {
				if data, err := os.ReadFile(c.files[0]); err == nil {
					if d := decodeImage([]Representation{{UTI: uti, Data: data}}); d != nil {
						if int64(len(d.png)) > maxBytes {
							return Record{}, "too-large"
						}
						return imageRecord(d, nil, ""), ""
					}
				}
			}
		}
	}
	// Files come before images: Finder adds a file-icon TIFF to every file copy.
	if len(c.files) > 0 {
		var reps []Representation
		for _, r := range c.reps {
			if r.UTI == utiFileURL || r.UTI == utiText8 {
				reps = append(reps, r)
			}
		}
		return Record{Kind: KindFile, Fingerprint: filesFingerprint(c.files), FilePaths: c.files,
			Title: DeriveTitle(KindFile, "", "", "", c.files, len(c.files), 0, 0), Preview: Preview(KindFile, "", "", "", c.files, 0, 0),
			Reps: reps, ByteSize: sumBytes(reps)}, ""
	}
	plain := NormalizeText(strings.Join(c.texts, "\n"))
	if plain == "" && c.html != "" {
		plain = NormalizeText(htmlToText(c.html))
	}
	if plain == "" && c.rtf != nil {
		plain = NormalizeText(rtfToText(string(c.rtf)))
	}
	if len(c.imageReps) > 0 {
		if d := decodeImage(c.imageReps); d != nil {
			if int64(len(d.png)) > maxBytes {
				return Record{}, "too-large"
			}
			var other []Representation
			for _, r := range c.reps {
				if !isImageType(r.UTI) {
					other = append(other, r)
				}
			}
			return imageRecord(d, other, c.html), ""
		}
		if plain == "" && c.url == "" {
			return Record{}, "image-decode-failed"
		}
	}
	if plain == "" && c.url == "" {
		return Record{}, "empty"
	}
	cl := classifyText(plain, c.url)
	stored := plain
	if cl.kind == KindLink && plain == "" {
		stored = cl.url
	}
	var reps []Representation
	for _, r := range c.reps {
		if !isImageType(r.UTI) && r.UTI != utiFileURL {
			reps = append(reps, r)
		}
	}
	rich := cl.kind == KindText && (c.html != "" || c.hasRTF)
	rec := Record{Kind: cl.kind, SubKind: cl.subKind, IsRich: rich, Fingerprint: cl.fingerprint, PlainText: stored, URL: cl.url,
		Color: cl.color, Title: DeriveTitle(cl.kind, stored, cl.url, cl.color, nil, 0, 0, 0),
		Preview: Preview(cl.kind, stored, cl.url, cl.color, nil, 0, 0), Reps: reps, ByteSize: sumBytes(reps),
		CharCount: len([]rune(stored)), Tags: cl.tags}
	if rich {
		rec.HTML = c.html
	}
	return rec, ""
}
